// Generates src/api/generated.ts from the FastAPI OpenAPI schema. Runs the app factory in Python (no server, no network).
import { execFileSync } from "node:child_process";
import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import path from "node:path";
import openapiTS, { astToString } from "openapi-typescript";

const here = path.dirname(fileURLToPath(import.meta.url));
const repo = path.resolve(here, "..", "..");
const py = path.join(repo, ".venv", "bin", "python");
const json = execFileSync(py, ["-W", "ignore", "-c", "import json; from api.main import create_app; print(json.dumps(create_app().openapi()))"], {
  cwd: repo,
  env: { ...process.env, INTAKE_DATA_DIR: path.join(repo, "tmp", "openapi_gen") },
  encoding: "utf-8",
});
const schema = JSON.parse(json);
const ast = await openapiTS(schema, { exportType: true });
const header = "// Generated by `npm run gen:api` from the FastAPI OpenAPI schema. Do not edit by hand.\n\n";
writeFileSync(path.join(here, "..", "src", "api", "generated.ts"), header + astToString(ast));
console.log(`wrote src/api/generated.ts (${Object.keys(schema.paths).length} paths)`);
